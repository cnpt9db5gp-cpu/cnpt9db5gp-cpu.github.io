#!/usr/bin/env python3
"""Generate js/menu.data.js from data/menu.json.

Ships the data as an ES module rather than fetching JSON, so index.html opens
straight from file:// with no web server (fetch of a local .json is blocked by
CORS). Re-run after editing menu.json.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "menu.json"
DST = ROOT / "js" / "menu.data.js"
BRAND = ROOT / "data" / "brand.json"

menu = json.loads(SRC.read_text(encoding="utf-8"))
if BRAND.exists():
    menu["brand"] = json.loads(BRAND.read_text(encoding="utf-8"))

js = (
    "// GENERATED by tools/build_data.py from data/menu.json - do not edit by hand.\n"
    "// A module, not a fetch of JSON, so index.html opens from file:// with no server.\n"
    "export default " + json.dumps(menu, ensure_ascii=False, indent=2) + ";\n"
)
DST.write_text(js, encoding="utf-8")
print(f"wrote {DST.relative_to(ROOT)}  {len(js)} bytes  "
      f"({menu['meta']['itemCount']} items, {menu['meta']['categoryCount']} categories)")
